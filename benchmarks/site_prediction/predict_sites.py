def _target_dirs(normalized_root: Path, dataset: str, targets: str | None) -> list[Path]:
    dataset_root = normalized_root / dataset
    if not dataset_root.is_dir():
        raise FileNotFoundError(f"normalized dataset not found: {dataset_root}")
    all_targets = sorted(path for path in dataset_root.iterdir() if (path / "receptor_input.pdb").is_file())
    if not targets or targets == "all":
        return all_targets
    wanted = {name.strip() for name in targets.split(",") if name.strip()}
    return [path for path in all_targets if path.name in wanted]


def _run(command: list[str], *, cwd: Path) -> None:
    subprocess.run(command, cwd=cwd, check=True)


def _preflight_method_tools(args: argparse.Namespace) -> None:
    if args.method == "cav-emps":
        try:
            resolved = resolve_autogrid4_bin(
                args.autogrid4_bin,
                auto_build_bundled=bool(args.auto_build_autogrid),
                numwi=int(args.numwi),
            )
        except (OSError, RuntimeError, subprocess.CalledProcessError) as exc:
            raise SystemExit(f"AutoGrid build/check failed for cav-emps: {exc}") from exc
        if resolved:
            args.autogrid4_bin = resolved
            return
        raise SystemExit(
            "Missing autogrid4 executable for cav-emps. "
            "Pass --autogrid4-bin, or let Ultidock build the bundled AutoGrid source "
            "by omitting --no-auto-build-autogrid."
        )
    if args.method == "fpocket" and not command_is_available(args.fpocket_cmd):
        token = first_command_token(args.fpocket_cmd) or "fpocket"
        raise SystemExit(f"Missing fpocket executable for fpocket method: {token}")
    if args.method == "p2rank" and not command_is_available(args.p2rank_cmd):
        token = first_command_token(args.p2rank_cmd) or "prank"
        raise SystemExit(f"Missing P2Rank executable for p2rank method: {token}")


def _write_cav_emps_runtime_config(args: argparse.Namespace) -> Path:
    config_dir = Path(args.output_dir).resolve() / "cav-emps" / "_runtime_config"
    config_dir.mkdir(parents=True, exist_ok=True)
    scratch_root = Path(args.output_dir).resolve() / "cav-emps" / "_runtime"
    values = _load_docking_config_defaults()
    values.update(
        {
            "AUTODOCK_GPU_DIR": str((REPO_ROOT / "docking" / "AUTODOCK_GPU_DIR").resolve()),
            "DOCKING_DIR": str(scratch_root / "DOCKING_DIR"),
            "RESULTS_DIR": str(scratch_root / "RESULTS_DIR"),
            "NUMWI": str(int(args.numwi)),
            "LIGANDS_DIR": str(scratch_root / "LIGANDS_DIR"),
            "CENTERS_TSV": None,
            "GRID_MODE": "centers",
            "GRID_SPACING": float(args.grid_spacing),
            "GRID_MARGIN": 5.0,
            "GRID_CAP": float(args.blind_cap),
            "AUTO_GRID_BIN": str(Path(args.autogrid4_bin).resolve()),
            "AUTOSITES": int(args.autosites),
            "BENCHMARK_MODE": True,
        }
    )
    if args.r_min is not None:
        values["R_MIN_CAVITY_A"] = float(args.r_min)

    lines = [
        "# Auto-generated by benchmarks/site_prediction/predict_sites.py",
        "# Scratch CaV-EMPS config for normalized site-prediction benchmarks.",
    ]
    for key, value in values.items():
        lines.append(f"{key} = {value!r}")
    (config_dir / "config.py").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return config_dir


def _load_cav_emps_make_grids(args: argparse.Namespace):
    config_dir = _write_cav_emps_runtime_config(args)
    config_dir_str = str(config_dir)
    docking_root_str = str(DOCKING_ROOT)
    for path in (config_dir_str, docking_root_str):
        while path in sys.path:
            sys.path.remove(path)
    sys.path.insert(0, docking_root_str)
    sys.path.insert(0, config_dir_str)
    sys.modules.pop("config", None)
    sys.modules.pop("make_grids", None)
    importlib.invalidate_caches()
    return importlib.import_module("make_grids")


def _write_predictions(path: Path, rows: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fieldnames = [
        "target_id",
        "method",
        "rank",
        "site_id",
        "center_x",
        "center_y",
        "center_z",
        "score",
        "source",
    ]
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames, delimiter="\t")
        writer.writeheader()
        for row in sorted(rows, key=lambda item: (item["target_id"], int(item["rank"]))):
            writer.writerow(row)


def _write_failures(path: Path, results: list[dict[str, Any]]) -> None:
    failures = [result for result in results if result["status"] != "ok"]
    if not failures:
        if path.exists():
            path.unlink()
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(
            handle,
            fieldnames=["target_id", "method", "status", "error"],
            delimiter="\t",
        )
        writer.writeheader()
        for result in sorted(failures, key=lambda item: item["target_id"]):
            writer.writerow(
                {
                    "target_id": result["target_id"],
                    "method": normalize_method_name(result.get("method", "")) or "",
                    "status": result["status"],
                    "error": result["error"],
                }
            )


def _autogenerate_cav_emps_centers(make_grids, *, args: argparse.Namespace, **kwargs: Any) -> None:
    if getattr(args, "cav_emps_supports_map_types", False):
        kwargs["map_types"] = None
    make_grids.autogenerate_centers_tsv(**kwargs)


def _cav_emps_predictions(target_dir: Path, target_output: Path, args: argparse.Namespace) -> list[dict[str, Any]]:
    make_grids = args.make_grids_module
    receptor = target_dir / "receptor_input.pdb"
    prepared_dir = target_output / "prepared"
    prepared = prepared_dir / receptor_pdbqt_output_name(receptor)
    if args.force and prepared.exists():
        prepared.unlink()
    if not prepared.exists():
        prepare_receptor_pdbqt(
            input_path=receptor,
            output_path=prepared,
            prepare_command=args.receptor_prepare_command,
            seed=int(args.seed),
            timestamp="SITE_BENCHMARK",
        )
    centers_tsv = target_output / "centers.tsv"
    if args.force and centers_tsv.exists():
        centers_tsv.unlink()
    if args.keep_artifacts:
        _autogenerate_cav_emps_centers(
            make_grids,
            args=args,
            receptor_pdbqt=str(prepared),
            out_root=str(target_output / "maps"),
            centers_tsv_path=str(centers_tsv),
            n_sites=int(args.autosites),
            autogrid4_bin=str(args.autogrid4_bin),
            hotspot_box_ang=float(args.hotspot_box_size),
            mode="receptor_search",
        )
    else:
        work_root = Path(args.work_root)
        work_root.mkdir(parents=True, exist_ok=True)
        with tempfile.TemporaryDirectory(prefix=f"{target_dir.name}-", dir=work_root) as work_dir:
            _autogenerate_cav_emps_centers(
                make_grids,
                args=args,
                receptor_pdbqt=str(prepared),
                out_root=str(Path(work_dir) / "maps"),
                centers_tsv_path=str(centers_tsv),
                n_sites=int(args.autosites),
                autogrid4_bin=str(args.autogrid4_bin),
                hotspot_box_ang=float(args.hotspot_box_size),
                mode="receptor_search",
            )
    ranked = rank_centers_by_fitness(parse_scored_centers_tsv(centers_tsv))
    rows = []
    for rank, site in enumerate(ranked, start=1):
        x, y, z = site["center"]
        rows.append(
            {
                "target_id": target_dir.name,
                "method": "cav-emps",
                "rank": rank,
                "site_id": site["site_id"],
                "center_x": f"{x:.4f}",
                "center_y": f"{y:.4f}",
                "center_z": f"{z:.4f}",
                "score": "" if site.get("fitness_score") is None else f"{float(site['fitness_score']):.4f}",
                "source": str(centers_tsv.resolve()),
            }
        )
    return rows


def _fpocket_predictions(target_dir: Path, target_output: Path, args: argparse.Namespace) -> list[dict[str, Any]]:
    from run_fpocket_baseline import find_fpocket_output, parse_fpocket_output

    raw_dir = target_output / "raw" / "fpocket"
    if args.force and raw_dir.exists():
        shutil.rmtree(raw_dir)
    raw_dir.mkdir(parents=True, exist_ok=True)
    receptor = target_dir / "receptor_input.pdb"
    staged = raw_dir / receptor.name
    shutil.copy2(receptor, staged)
    _run([*shlex.split(args.fpocket_cmd), "-f", staged.name], cwd=raw_dir)
    sites = parse_fpocket_output(find_fpocket_output(raw_dir, staged))
    return [
        {
            "target_id": target_dir.name,
            "method": "fpocket",
            "rank": index,
            "site_id": site.site_id,
            "center_x": f"{site.center[0]:.4f}",
            "center_y": f"{site.center[1]:.4f}",
            "center_z": f"{site.center[2]:.4f}",
            "score": "" if site.score is None else f"{site.score:.4f}",
            "source": site.source,
        }
        for index, site in enumerate(sites[: int(args.autosites)], start=1)
    ]


def _p2rank_predictions(target_dir: Path, target_output: Path, args: argparse.Namespace) -> list[dict[str, Any]]:
    from run_p2rank_baseline import find_predictions_csv, parse_p2rank_predictions

    raw_dir = target_output / "raw" / "p2rank"
    if args.force and raw_dir.exists():
        shutil.rmtree(raw_dir)
    raw_dir.mkdir(parents=True, exist_ok=True)
    receptor = target_dir / "receptor_input.pdb"
    command = [*shlex.split(args.p2rank_cmd), "-f", str(receptor), "-o", str(raw_dir)]
    _run(command, cwd=raw_dir)
    sites = parse_p2rank_predictions(find_predictions_csv(raw_dir))
    return [
        {
            "target_id": target_dir.name,
            "method": "p2rank",
            "rank": index,
            "site_id": site.site_id,
            "center_x": f"{site.center[0]:.4f}",
            "center_y": f"{site.center[1]:.4f}",
            "center_z": f"{site.center[2]:.4f}",
            "score": "" if site.score is None else f"{site.score:.4f}",
            "source": site.source,
        }
        for index, site in enumerate(sites[: int(args.autosites)], start=1)
    ]


def run_one(target_dir: Path, args: argparse.Namespace) -> dict[str, Any]:
    method = normalize_method_name(args.method)
    target_output = Path(args.output_dir).resolve() / method / target_dir.name
    target_output.mkdir(parents=True, exist_ok=True)
    try:
        if method == "cav-emps":
            rows = _cav_emps_predictions(target_dir, target_output, args)
        elif method == "fpocket":
            rows = _fpocket_predictions(target_dir, target_output, args)
        elif method == "p2rank":
            rows = _p2rank_predictions(target_dir, target_output, args)
        else:
            raise ValueError(f"unsupported method: {args.method}")
        _write_predictions(target_output / "predictions.tsv", rows)
        print(f"[OK] {target_dir.name}: {len(rows)} {method} prediction(s)")
        return {"status": "ok", "target_id": target_dir.name, "method": method, "rows": rows, "error": ""}
    except Exception as exc:
        print(f"[FAIL] {target_dir.name}: {exc}", file=sys.stderr)
        return {
            "status": "failed",
            "target_id": target_dir.name,
            "method": method,
            "rows": [],
            "error": str(exc),
        }


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Generate cav-emps, fpocket, or p2rank predictions on normalized targets.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument("--dataset", required=True)
    parser.add_argument("--method", required=True, choices=SITE_PREDICTION_METHODS)
    parser.add_argument("--normalized-root", default=str(DEFAULT_NORMALIZED_ROOT), type=Path)
    parser.add_argument("--output-dir", default=str(DEFAULT_OUTPUT_DIR), type=Path)
    parser.add_argument("--targets", help="Comma-separated target IDs or all.")
    parser.add_argument("--max-targets", type=int)
    parser.add_argument("--jobs", type=int, default=1)
    parser.add_argument("--autosites", type=int, default=6)
    parser.add_argument("--force", action="store_true")
    parser.add_argument(
        "--keep-artifacts",
        action="store_true",
        help=(
            "Keep per-target CaV-EMPS AutoGrid maps in the result directory. "
            "By default, heavy map artifacts are written to temporary workdirs and removed."
        ),
    )
    parser.add_argument(
        "--work-root",
        type=Path,
        help=(
            "Temporary work root for heavy CaV-EMPS artifacts when --keep-artifacts is not set. "
            "Defaults to <output-dir>/<method>/_runtime/work."
        ),
    )
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--autogrid4-bin", default=str(DEFAULT_AUTOGRID4))
    parser.add_argument(
        "--no-auto-build-autogrid",
        dest="auto_build_autogrid",
        action="store_false",
        help="Do not compile the bundled AutoGrid source automatically for cav-emps.",
    )
    parser.set_defaults(auto_build_autogrid=True)
    parser.add_argument("--numwi", type=int, default=128, help="NUMWI passed to Ultidock's build script.")
    parser.add_argument("--grid-spacing", type=float, default=0.375)
    parser.add_argument("--blind-cap", type=float, default=150.0)
    parser.add_argument("--r-min", type=float)
    parser.add_argument("--hotspot-box-size", type=float, default=35.0)
    parser.add_argument("--receptor-prepare-command")
    parser.add_argument(
        "--full-autogrid-maps",
        action="store_true",
        help=(
            "Deprecated compatibility flag. CaV-EMPS site prediction always "
            "generates full AD4 ligand maps because AutoGrid dsolvmap depends "
            "on the requested ligand type set."
        ),
    )
    parser.add_argument("--fpocket-cmd", default="fpocket")
    parser.add_argument("--p2rank-cmd", default="prank predict")
    return parser


def run_predictions(args: argparse.Namespace) -> Path:
    args.method = normalize_method_name(args.method)
    output_root = Path(args.output_dir).resolve() / args.method
    if args.work_root is None:
        args.work_root = output_root / "_runtime" / "work"
    else:
        args.work_root = Path(args.work_root).resolve()
    _preflight_method_tools(args)
    args.make_grids_module = None
    if args.method == "cav-emps":
        args.make_grids_module = _load_cav_emps_make_grids(args)
        args.cav_emps_supports_map_types = (
            "map_types" in inspect.signature(args.make_grids_module.autogenerate_centers_tsv).parameters
        )
    else:
        args.cav_emps_supports_map_types = False
    target_dirs = _target_dirs(Path(args.normalized_root).resolve(), args.dataset, args.targets)
    if args.max_targets is not None:
        target_dirs = target_dirs[: args.max_targets]
    if not target_dirs:
        raise SystemExit("No normalized targets selected.")

    results = []
    with ThreadPoolExecutor(max_workers=max(1, int(args.jobs))) as executor:
        futures = {executor.submit(run_one, target_dir, args): target_dir for target_dir in target_dirs}
        for future in as_completed(futures):
            results.append(future.result())

    rows = [row for result in results for row in result["rows"]]
    _write_predictions(output_root / "predictions.tsv", rows)
    _write_failures(output_root / "failures.tsv", results)
    n_ok = sum(1 for result in results if result["status"] == "ok")
    n_failed = sum(1 for result in results if result["status"] != "ok")
    metadata = {
        "run_started_at_utc": datetime.now(timezone.utc).isoformat(),
        "dataset": args.dataset,
        "method": args.method,
        "n_targets": len(target_dirs),
        "n_ok": n_ok,
        "n_failed": n_failed,
        "n_prediction_rows": len(rows),
        "keep_artifacts": bool(args.keep_artifacts),
        "work_root": str(Path(args.work_root).resolve()),
    }
    if args.method == "cav-emps":
        metadata["autogrid_maps"] = "all"
        if not args.cav_emps_supports_map_types:
            metadata["autogrid_map_note"] = (
                "loaded make_grids.py does not support selective map generation"
            )
    output_root.mkdir(parents=True, exist_ok=True)
    (output_root / "run_metadata.json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")
    if n_ok == 0:
        raise SystemExit(
            f"{args.method} produced no successful target predictions for {args.dataset}; "
            f"see {output_root / 'failures.tsv'}"
        )
    if not rows:
        raise SystemExit(
            f"{args.method} produced zero prediction rows for {args.dataset}; "
            f"see {output_root / 'run_metadata.json'}"
        )
    print(f"Predictions TSV: {output_root / 'predictions.tsv'}")
    return output_root / "predictions.tsv"


def main() -> None:
    args = build_parser().parse_args()
    run_predictions(args)


if __name__ == "__main__":
    main()
